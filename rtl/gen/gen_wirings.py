"""Generate rtl/src/wirings_pkg.sv from data/wirings/enigma.txt.

The wiring file is the single source of truth shared with the Rust core; this script turns it
into packed constant tables plus lookup functions. Run from anywhere:

    python rtl/gen/gen_wirings.py
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "wirings" / "enigma.txt"
OUT = ROOT / "rtl" / "src" / "wirings_pkg.sv"

ROTOR_ORDER = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "BETA", "GAMMA"]
REFLECTOR_ORDER = ["B", "C", "B-THIN", "C-THIN"]


def parse() -> tuple[dict[str, str], dict[str, str]]:
    rotors: dict[str, str] = {}
    reflectors: dict[str, str] = {}
    for raw in SRC.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        kind, name, wiring, _turnover = line.split()
        name = name.upper()
        assert sorted(wiring) == [chr(65 + i) for i in range(26)], f"{name}: not a permutation"
        (reflectors if kind == "reflector" else rotors)[name] = wiring
    assert list(rotors) == ROTOR_ORDER, list(rotors)
    assert list(reflectors) == REFLECTOR_ORDER, list(reflectors)
    return rotors, reflectors


def packed(tables: list[list[int]]) -> str:
    """Entry [id][c] at bits ((id*26 + c)*5) +: 5, as one hex literal."""
    value = 0
    for i, table in enumerate(tables):
        for c, out in enumerate(table):
            value |= out << ((i * 26 + c) * 5)
    width = len(tables) * 26 * 5
    return f"{width}'h{value:0{(width + 3) // 4}x}"


def main() -> None:
    rotors, reflectors = parse()
    fwd = [[ord(ch) - 65 for ch in rotors[n]] for n in ROTOR_ORDER]
    bwd = [[row.index(c) for c in range(26)] for row in fwd]
    refl = [[ord(ch) - 65 for ch in reflectors[n]] for n in REFLECTOR_ORDER]

    ids = "\n".join(f"//   {i}: {n}" for i, n in enumerate(ROTOR_ORDER))
    rids = "\n".join(f"//   {i}: {n}" for i, n in enumerate(REFLECTOR_ORDER))
    OUT.write_text(
        f"""// GENERATED by rtl/gen/gen_wirings.py from data/wirings/enigma.txt — do not edit.
//
// Rotor ids:
{ids}
// Reflector ids:
{rids}
//
// Tables are packed: entry [id][c] lives at bits ((id*26 + c)*5) +: 5.

package wirings_pkg;

  localparam int NUM_ROTORS = {len(ROTOR_ORDER)};
  localparam int NUM_REFLECTORS = {len(REFLECTOR_ORDER)};

  localparam logic [NUM_ROTORS*26*5-1:0] ROTOR_FWD = {packed(fwd)};
  localparam logic [NUM_ROTORS*26*5-1:0] ROTOR_BWD = {packed(bwd)};
  localparam logic [NUM_REFLECTORS*26*5-1:0] REFLECTOR = {packed(refl)};

  // Functions use Verilog-2001 style (no casts, no `return`) so that Verilator, Icarus and the
  // Yosys built-in front end all accept them.

  // (a + b) mod 26 for letters a, b in 0..25.
  function automatic [4:0] add26(input [4:0] a, input [4:0] b);
    reg [5:0] s;
    begin
      s = {{1'b0, a}} + {{1'b0, b}};
      if (s >= 6'd26) s = s - 6'd26;
      add26 = s[4:0];
    end
  endfunction

  // (a - b) mod 26 for letters a, b in 0..25.
  function automatic [4:0] sub26(input [4:0] a, input [4:0] b);
    reg [5:0] s;
    begin
      s = {{1'b0, a}} + 6'd26 - {{1'b0, b}};
      if (s >= 6'd26) s = s - 6'd26;
      sub26 = s[4:0];
    end
  endfunction

  // Signal through a rotor whose core is turned by `core`, entry side -> reflector side.
  function automatic [4:0] rotor_fwd(input [3:0] id, input [4:0] core, input [4:0] c);
    reg [4:0] x;
    begin
      x = ROTOR_FWD[({{6'd0, id}} * 10'd26 + {{5'd0, add26(c, core)}}) * 5 +: 5];
      rotor_fwd = sub26(x, core);
    end
  endfunction

  // Signal through a rotor whose core is turned by `core`, reflector side -> entry side.
  function automatic [4:0] rotor_bwd(input [3:0] id, input [4:0] core, input [4:0] c);
    reg [4:0] x;
    begin
      x = ROTOR_BWD[({{6'd0, id}} * 10'd26 + {{5'd0, add26(c, core)}}) * 5 +: 5];
      rotor_bwd = sub26(x, core);
    end
  endfunction

  function automatic [4:0] reflect(input [1:0] id, input [4:0] c);
    begin
      reflect = REFLECTOR[({{8'd0, id}} * 10'd26 + {{5'd0, c}}) * 5 +: 5];
    end
  endfunction

endpackage
""",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
