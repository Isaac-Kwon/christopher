#!/usr/bin/env python3
"""Generate offset_dial.kicad_pcb: deterministic PLACEMENT only (no tracks, vias or zones; routing by hand).

    python gen_dial_pcb.py [OUTDIR]     # board + design rules merged into the .kicad_pro (stdlib; kicad-cli for the netlist)

Board 116 x 58 mm, 2 layers, one per unit (12 identical boards on the dial strip, pitch 120; layout.md 3.5):
    F side (faces into the machine): the code tracks (pads of the generated footprint SW1, centre (29, 29)), the vertical
             D-sub 15 J1 (to the counter unit board J2), the rotor, detent and rear bracket (README 4)
    B side (faces the visitor):      the letter scale A-Z around the knob (B.SilkS, mirrored so it reads from the front)
    corners: four plated M3 holes (CHASSIS) for the standoffs of the faceplate and of the rear bracket
The code-track pads of one ring are one net each; joining them to J1 is routing (ratsnest).
"""
from __future__ import annotations

import sys
import uuid
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "position-display"))
import kigen  # noqa: E402
import verify_counter as vc  # noqa: E402
import dialmech as M  # noqa: E402
import gen_dial  # noqa: E402

PROJECT = "offset_dial"
NS = uuid.UUID("9a4c2e61-7b3d-4f08-b5e2-1c6d8f0a3e22")
W, H = M.BOARD
HOLES = [(5.0, 5.0), (W - 5.0, 5.0), (5.0, H - 5.0), (W - 5.0, H - 5.0)]


def custom(fp_text: str | None = None) -> dict:
    return {f"{gen_dial.LIB}:{gen_dial.FPNAME}": fp_text if fp_text is not None else
            (HERE / f"{gen_dial.LIB}.pretty" / f"{gen_dial.FPNAME}.kicad_mod").read_text(encoding="utf8")}


def placements(nl) -> tuple[dict, str]:
    P = {"SW1": (M.CENTER[0], M.CENTER[1], 0, False)}
    xmin, xmax, ymin, ymax = kigen.courtyard(nl.parts["J1"]["footprint"])
    P["J1"] = (70.0, M.CENTER[1] - (ymin + ymax) / 2, 0, False)
    for k, (x, y) in enumerate(HOLES, 1):
        P[f"H{k}"] = (x, y, 0, True)
    gt = lambda key, text, x, y, size, **k: kigen.gr_text(NS, PROJECT, key, text, x, y, size, **k)
    extra = (gt("t1", "OFFSET DIAL - rotor side (F): code tracks, comb, detent", 85.0, 8.0, 1.2, thick=0.18, just="center")
             + gt("t2", "J1 DIAL -> counter unit J2 (1:1 D-sub 15 cable)", 85.0, 44.5, 1.2, thick=0.18, just="center")
             + gt("t3", "UNIT", 85.0, 50.0, 2.0, layer="B.SilkS", mirror=True, thick=0.3, just="center")
             + kigen.gr_rect(NS, PROJECT, "unitbox", 74.0, 47.0, 22.0, 6.0, layer="B.SilkS", width=0.2, dash=False))
    return P, extra


def build(nl, fp_text: str | None = None) -> tuple[str, dict]:
    P, extra = placements(nl)
    text = kigen.board_text(NS, PROJECT, "Offset dial (module N): 26-position code-track rotary switch",
                            ["Generated by gen_dial_pcb.py - placement only, routing by hand",
                             "F side = rotor side (code tracks, D-sub); B side = visitor side (letter scale)"],
                            nl, P, W, H, layers4=False, extra=extra, custom=custom(fp_text))
    return text, P


def generate(outdir: Path):
    outdir.mkdir(parents=True, exist_ok=True)
    work = kigen.build_dir("offset-dial")
    net = kigen.export_netlist(HERE / f"{PROJECT}.kicad_sch", work / "pcb_netlist.net")
    nl = vc.Netlist(net.read_text(encoding="utf8"))
    text, P = build(nl)
    (outdir / f"{PROJECT}.kicad_pcb").write_text(text, encoding="utf8", newline="\n")
    kigen.merge_project(outdir / f"{PROJECT}.kicad_pro", [("Default", 0.2, 0.5, 0.25)], [])
    print(f"wrote {PROJECT}.kicad_pcb ({len(P)} parts, {W:g} x {H:g} mm, 2 layers) and board rules in {PROJECT}.kicad_pro")


if __name__ == "__main__":
    generate(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE)
