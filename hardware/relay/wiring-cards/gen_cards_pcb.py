#!/usr/bin/env python3
"""Generate the KiCad 10 PCBs of the relay wiring cards: deterministic PLACEMENT only (no routing).

    python gen_cards_pcb.py       # rotor_I..VIII and reflector_B/C: .kicad_pcb + board rules in the .kicad_pro

Outline (250 x 228 mm), the four plated M3 holes (net CHASSIS), the D-sub 37 footprint and the connector
poses are those of the relay shifter board (hardware/relay/shifter-board/gen_shifter_pcb.py): J1/J2 on the
left edge, J3/J4 on the right edge, at the same coordinates and rotations, so that the stack's straight ribbons
reach the same positions on every card.  A W card carries all four connectors, a U card only J3 and J2.  The
verifier (verify_cards_pcb.py) compares these poses with the shifter board file itself.
Two copper layers (the cards are passive); the netlist is imported so that the ratsnest shows the wiring.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import gen_cards as C
import ki_common as K

HERE = Path(__file__).resolve().parent
UID_NS = "6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0f02"

# ---- geometry copied from gen_shifter_pcb.py (checked against shifter_board.kicad_pcb by verify_cards_pcb.py)
BOARD_W, BOARD_H = 250.0, 228.0
CONN_DEPTH = 12.74
TOP, SPAN, GAP = 12.0, 70.41, 3.6
CONN_POSE = {                       # ref -> (x, y, rot): pin 1 of the D-sub is the footprint origin
    "J1": (CONN_DEPTH, TOP + 10.28, 270),
    "J2": (CONN_DEPTH, TOP + SPAN + GAP + 10.28, 270),
    "J3": (BOARD_W - CONN_DEPTH, TOP + 60.13, 90),
    "J4": (BOARD_W - CONN_DEPTH, TOP + SPAN + GAP + 60.13, 90),
}
HOLES = [(5.0, 5.0), (BOARD_W - 5.0, 5.0), (5.0, BOARD_H - 5.0), (BOARD_W - 5.0, BOARD_H - 5.0)]


def placements(nl: K.Netlist) -> dict:
    P = {ref: dict(x=x, y=y, rot=rot) for ref, (x, y, rot) in CONN_POSE.items() if ref in nl.parts}
    for k, (x, y) in enumerate(HOLES, 1):
        P[f"H{k}"] = dict(x=x, y=y, rot=0, hide=True)
    return P


def silk(uid: K.Ids, kind: str, name: str, nl: K.Netlist) -> str:
    """Silkscreen on the component side: card name, wiring, orientation, connector functions."""
    o = ""
    cx = BOARD_W / 2
    if kind == "rotor":
        w = C.table("rotor", name)
        o += K.gr_text(uid, "t1", f"ROTOR {name}  (W CARD)", cx, 92.0, 0, "F.SilkS", 4.0, 0.5)
        o += K.gr_text(uid, "t2", "ABCDEFGHIJKLMNOPQRSTUVWXYZ", cx, 104.0, 0, "F.SilkS", 2.0, 0.3)
        o += K.gr_text(uid, "t3", "".join(C.L(x) for x in w), cx, 110.0, 0, "F.SilkS", 2.0, 0.3)
        o += K.gr_text(uid, "t4", "OUTBOUND J3 -> J1 = W    RETURN J4 -> J2 = W INVERSE", cx, 120.0, 0, "F.SilkS", 1.5, 0.2)
    else:
        r = C.table("reflector", name)
        o += K.gr_text(uid, "t1", f"REFLECTOR {name}  (U CARD)", cx, 92.0, 0, "F.SilkS", 4.0, 0.5)
        o += K.gr_text(uid, "t2", "ABCDEFGHIJKLMNOPQRSTUVWXYZ", cx, 104.0, 0, "F.SilkS", 2.0, 0.3)
        o += K.gr_text(uid, "t3", "".join(C.L(x) for x in r), cx, 110.0, 0, "F.SilkS", 2.0, 0.3)
        o += K.gr_text(uid, "t4", "OUTBOUND J3 -> RETURN J2 (LINE I TO R[I])", cx, 120.0, 0, "F.SilkS", 1.5, 0.2)
    o += K.gr_text(uid, "t5", "STACK: COMPONENT SIDE FACES THE BACK. IN EDGE = BOTTOM (J3 J4), OUT EDGE = TOP (J1 J2)",
                   cx, 136.0, 0, "F.SilkS", 1.5, 0.2)
    o += K.gr_text(uid, "t6", "PIN 1-26 = LINES A-Z, 27-37 NOT CONNECTED. RELAY UNIT, SEE README.MD", cx, 142.0, 0,
                   "F.SilkS", 1.5, 0.2)
    funcs = C.W_CONN if kind == "rotor" else C.U_CONN
    for ref, fn in funcs.items():
        x, y, rot = CONN_POSE[ref]
        side = ref in ("J1", "J2")
        tx = 28.0 if side else BOARD_W - 28.0
        ty = y + (25.0 if side else -25.0)
        o += K.gr_text(uid, f"c{ref}", f"{ref} {fn}", tx, ty, 90, "F.SilkS", 1.8, 0.25)
    return o


def build(proj: str, kind: str, name: str, nl: K.Netlist) -> str:
    uid = K.Ids(UID_NS)
    lib = K.FpLib()
    netid, node_net = K.assign_nets(nl)
    for ref in nl.parts:                     # D-sub shells (footprint pads "SH") are CHASSIS (0003 7.1)
        if ref.startswith("J"):
            node_net[(ref, "SH")] = (netid["/CHASSIS"], "/CHASSIS")
    P = placements(nl)
    missing = set(nl.parts) - set(P)
    assert not missing, f"unplaced parts: {sorted(missing)}"
    title = (f"Relay rotor wiring card W: rotor {name}" if kind == "rotor" else f"Relay reflector card U: reflector {name}")
    o = [K.pcb_header("gen_cards_pcb.py", title, "A3",
                      ["Generated by gen_cards_pcb.py - placement only, routing by hand",
                       f"Netlist from {proj}.kicad_sch; 2 layers; outline and J1-J4 poses of the shifter board"],
                      four_layers=False), '\t(net 0 "")\n']
    for n, i in netid.items():
        o.append(f'\t(net {i} "{n}")\n')
    for ref in sorted(P):
        p = P[ref]
        part = nl.parts[ref]
        o.append(K.place(lib, uid, part["footprint"], ref, part["value"], p["x"], p["y"], p.get("rot", 0),
                         {pin: node_net[(r, pin)] for (r, pin) in node_net if r == ref}, hide_ref=p.get("hide", False)))
    o.append(K.edge_rect(uid, BOARD_W, BOARD_H))
    o.append(silk(uid, kind, name, nl))
    o.append(")\n")
    return "".join(o)


def main():
    for proj, kind, name in C.all_cards():
        with tempfile.TemporaryDirectory() as td:
            nl = K.Netlist.export(HERE / f"{proj}.kicad_sch", Path(td))
        (HERE / f"{proj}.kicad_pcb").write_text(build(proj, kind, name, nl), encoding="utf8", newline="\n")
        K.merge_board_rules(HERE / f"{proj}.kicad_pro", track=0.2, clear=0.15, via_d=0.5, via_drill=0.25)
        print(f"wrote {proj}.kicad_pcb")


if __name__ == "__main__":
    main()
