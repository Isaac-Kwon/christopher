#!/usr/bin/env python3
"""Generate the KiCad 10 project + hierarchical schematic of the relay machine's CLOCK SEQUENCER board.

Design: README.md; interface: docs/decisions/0003-interfaces.md (control connector, L1-L9, K7); counters: counter-board README.
The circuit itself (parts, nets) is in seqdesign.py.  Stdlib only; library symbols are copied from the installed KiCad
libraries (env KICAD_SHARE overrides the default install location).

    python gen_sequencer.py        # writes sequencer.kicad_pro/.kicad_sch + the sub-sheets next to this file

Sheets:  POWER  TIMEBASE (555 + ring counter + windows)  DRIVERS (TBD62783A)  INPUTS (follower relays)  LOGIC (state relays)
         OUTPUTS (output relays, fuses)  CONNECTORS
Every net name is global (label '@'), so the exported netlist has plain names.
"""
from __future__ import annotations

import sys
from pathlib import Path

import kisheet
from kisheet import G, PROJECT, Sheet, f, g, sheet_block, uid
from kilib import Sym
import seqdesign

HERE = Path(__file__).resolve().parent

SYM = {
    "T2": Sym("Connector", "Screw_Terminal_01x02"), "T4": Sym("Connector", "Screw_Terminal_01x04"),
    "F": Sym("Device", "Polyfuse"), "QP": Sym("Transistor_FET", "Q_PMOS_GDS"), "DZ": Sym("Device", "D_Zener"),
    "D": Sym("Device", "D"), "DS": Sym("Device", "D_Schottky"), "R": Sym("Device", "R_US"), "C": Sym("Device", "C"),
    "CP": Sym("Device", "C_Polarized"), "TVS": Sym("Diode", "SMAJ33A"), "TSR": Sym("Converter_DCDC", "TSR_1-2450"),
    "LED": Sym("Device", "LED"), "HOLE": Sym("Mechanical", "MountingHole_Pad"), "555": Sym("Timer", "LMC555xM"),
    "POT": Sym("Device", "R_Potentiometer_Trim"), "4017": Sym("4xxx", "4017"), "TBD": Sym("Transistor_Array", "TBD62783A"),
    "K": Sym("Relay", "G6S-2"), "SJO": Sym("Jumper", "SolderJumper_2_Open"), "SJB": Sym("Jumper", "SolderJumper_2_Bridged"),
    "DC37": Sym("Connector", "DC37_Pins"), "DE9": Sym("Connector", "DE9_Pins"), "DB25": Sym("Connector", "DB25_Pins"),
}
# cell size (x pitch, y pitch) per kind for the automatic placement on a sheet
CELL = {"K": (62, 46), "DC37": (60, 130), "DB25": (50, 100), "DE9": (50, 60), "TBD": (60, 70), "4017": (60, 70), "555": (60, 50),
        "T2": (40, 20), "T4": (40, 30), "TSR": (50, 30)}
SHEETS = [("POWER", "power"), ("TIMEBASE", "timebase"), ("DRIVERS", "drivers"), ("INPUTS", "inputs"), ("LOGIC", "logic"),
          ("OUTPUTS", "outputs"), ("CONNECTORS", "connectors")]
TITLES = {
    "power": "Power: +24V_SW input, series P-MOSFET, TVS, 5 V for the clock",
    "timebase": "Time base: LMC555 astable (6 ms tick) + 74HC4017 ring counter + diode-OR windows",
    "drivers": "TBD62783A high-side drivers for the relays the ring drives",
    "inputs": "Input follower relays: RUN, STOP_LATCH, HOME, POS10 / POS13 / POS14 (0003 2.2: series diode, clamp on the coil side)",
    "logic": "State and gating relays (24 V relay logic)",
    "outputs": "Output relays (STROBE, JUDGE, CLEAR, CK/NCK buses A and B, KEN, LOAD) and output fuses",
    "connectors": "Connectors: J2 control (0003 5.2), J3/J4 CLOCK buses, J5 POS in, J6 UNIT_BUS tap, J7 safety loops, J8 timer, J9 thermostat",
}


def place_sheet(sh: Sheet, parts, ref_fixed=None):
    x0, y0, xmax = 30.0, 40.0, 780.0
    x, y, rowh = x0, y0, 0.0
    for p in parts:
        sym = SYM[p.kind]
        cw, ch = CELL.get(p.kind, (34, 18))
        if x + cw > xmax:
            x, y, rowh = x0, y + rowh + 6, 0.0
        px, py = x + cw / 2, y + ch / 2
        nets = {k: "@" + v for k, v in p.nets.items()}
        if p.kind == "T4" or p.kind == "T2":
            pass
        sh.place(sym, px, py, p.ref, p.value, p.fp, nets, unit=p.unit, nc=p.nc, desc=p.desc, ds=p.ds, in_bom=p.bom,
                 show_value=p.kind in ("K", "U", "R", "C", "CP", "T2", "T4", "DC37", "DE9", "DB25", "555", "4017", "TBD", "TSR", "SJO", "SJB", "POT"),
                 stub=7.62 if p.kind in ("DC37", "DB25", "DE9", "4017", "555", "TBD", "K") else 5.08)
        x += cw
        rowh = max(rowh, ch)


def main(outdir: Path = HERE):
    d = seqdesign.build()
    root_uuid = uid("file", "root")
    orig_init = Sheet.__init__

    def init(self, key, *a, **k):
        orig_init(self, key, *a, **k)
        self.path = f"/{root_uuid}/{uid('sheet', key)}" if key != "root" else f"/{root_uuid}"

    Sheet.__init__ = init
    sheets = []
    for name, key in SHEETS:
        sh = Sheet(key, TITLES[key], [f"Project Christopher - relay machine clock sequencer; sheet {name}",
                                      "Generated by gen_sequencer.py - do not edit by hand", "Design: hardware/relay/sequencer/README.md"], paper="A0")
        parts = [p for p in d.parts if p.sheet == key]
        place_sheet(sh, parts)
        if key == "power":
            for net, (fx, fy) in (("SW", (20, 20)), ("GND", (60, 20))):
                sh.flag(net, fx, fy)
        sheets.append((name, key, sh))
    root = Sheet("root", "Relay machine clock sequencer (CK/NCK, STROBE/JUDGE/CLEAR, HOME/LOAD, END, standby)",
                 ["Project Christopher - relay bank clock sequencer 'Q' (hardware/relay/layout.md 3.5: 250 x 228 x 40 card)",
                  "Generated by gen_sequencer.py - do not edit by hand", "Design: hardware/relay/sequencer/README.md"], paper="A2")
    for i, (name, key, sh) in enumerate(sheets):
        root.items.append(sheet_block(uid("sheet", key), root_uuid, name, f"{key}.kicad_sch", 30 + (i % 4) * 90, 40 + (i // 4) * 40, 60, 20, i + 2))
    root.text("Relay machine clock sequencer: 37 G6S-2 relays do the sequencing (windows -> relay contacts); the only active timing part is one\n"
              "LMC555 + one 74HC4017 (the 'when' of the position cycle).  Stop / run / home / end decisions are relay contacts.\n"
              "See README.md: principle, timetable, verification.", 30, 20, 1.8)
    pro = outdir / f"{PROJECT}.kicad_pro"
    if not pro.exists():
        pro.write_text(PRO % PROJECT, encoding="utf8", newline="\n")
    (outdir / f"{PROJECT}.kicad_sch").write_text(root.render(), encoding="utf8", newline="\n")
    for name, key, sh in sheets:
        (outdir / f"{key}.kicad_sch").write_text(sh.render(), encoding="utf8", newline="\n")
    print(f"wrote {PROJECT}.kicad_sch + {len(sheets)} sheets to {outdir}; {len(d.parts)} parts, {len(d.relays)} relays")


PRO = """{
  "meta": {
    "filename": "%s.kicad_pro",
    "version": 3
  },
  "schematic": {
    "drawing": {
      "default_line_thickness": 6.0,
      "default_text_size": 50.0
    }
  },
  "sheets": [],
  "text_variables": {}
}
"""

if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE)
