#!/usr/bin/env python3
"""Generate the KiCad 10 PCBs of the gear column wiring: deterministic PLACEMENT only (no routing).

    python gen_contact_pcb.py [--contacts-cw]     # contact_board, column_terminal, reflector_B, reflector_C

contact_board (110 x 110, 4 layers): 104 Omniball footprints exactly on the rings r = 22/29/36/43 mm about the board
centre, position j at -j x 13.846 deg (counter-clockwise seen from the contact side; j = 0 = A at 12 o'clock, the drum
index mark) - the mirror image of the drum's clockwise letters seen from its pad side (README.md); --contacts-cw
mirrors the board.  The four 2 x 13 IDC headers are on the BACK in the four corners (45 deg), pin 1 at the board edge
side, ring 1/2 on the left, ring 3/4 on the right, ring 2/3 at the top, ring 1/4 at the bottom, so that the
ribbons between stations run straight up/down.  Centre hole Ø38, posts at (+-48, +-48) mm.
"""
from __future__ import annotations

import math
import sys
import tempfile
from pathlib import Path

import gen_contact as C
import ki_common as K

HERE = Path(__file__).resolve().parent
UID_NS = "6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0e02"
CX, CY = C.CENTER
HDR_RADIAL = 50.9          # centre of the 9.95 mm courtyard at radius 50.9 -> inner edge 45.95, outer 55.9
HDR_HALF_LEN = 15.24       # half of the pin array (12 x 2.54 / 2)

# corner -> (radial unit vector, direction of increasing pin number); y grows downwards (KiCad)
S2 = math.sqrt(0.5)
CORNERS = {"TL": ((-S2, -S2), (S2, -S2)), "BL": ((-S2, S2), (S2, S2)),
           "TR": ((S2, -S2), (-S2, -S2)), "BR": ((S2, S2), (-S2, S2))}


def contact_xy(ring: int, j: int, ccw: bool = True) -> tuple[float, float]:
    a = math.radians((-1 if ccw else 1) * j * C.DELTA)
    r = C.RING_R[ring]
    return CX + r * math.sin(a), CY - r * math.cos(a)


def header_pose(corner: str) -> tuple[float, float, float]:
    """(pin-1 x, pin-1 y, stored rotation) of a back-side 2 x 13 vertical IDC header in a corner."""
    n, u = CORNERS[corner]
    theta = math.degrees(math.atan2(-u[0], -u[1])) % 360          # u = (-sin t, -cos t) for a back-side footprint
    v = (math.cos(math.radians(theta)), -math.sin(math.radians(theta)))
    cx, cy = CX + HDR_RADIAL * n[0], CY + HDR_RADIAL * n[1]
    x1 = cx - HDR_HALF_LEN * u[0] - 1.27 * v[0]
    y1 = cy - HDR_HALF_LEN * u[1] - 1.27 * v[1]
    return x1, y1, theta


def station_placements(ccw=True) -> dict:
    P = {}
    for ring in (1, 2, 3, 4):
        for j in range(C.N):
            x, y = contact_xy(ring, j, ccw)
            P[C.contact_ref(ring, j)] = dict(x=x, y=y, rot=0, hide=True)
    for h, corner in C.CORNER_ORDER.items():
        x, y, th = header_pose(corner)
        P[h] = dict(x=x, y=y, rot=th, flip=True, hide=True)
    return P


def station_extra(uid: K.Ids, ccw: bool) -> str:
    h = C.BOARD / 2
    o = K.edge_rect(uid, C.BOARD, C.BOARD, CX - h, CY - h)
    o += K.edge_circle(uid, "bore", (CX, CY), C.CENTRE_HOLE_D / 2)
    # silkscreen on the contact (front) side: letters outside ring 4, ring numbers at the index mark, index triangle
    for j in range(C.N):
        x, y = contact_xy(4, j, ccw)
        ang = (-1 if ccw else 1) * j * C.DELTA
        a = math.radians(ang)
        tx, ty = CX + 48.6 * math.sin(a), CY - 48.6 * math.cos(a)
        o += K.gr_text(uid, f"let{j}", C.L(j), tx, ty, -ang, "F.SilkS", 1.5, 0.2)
    for ring in (1, 2, 3, 4):
        o += K.gr_text(uid, f"ring{ring}", f"R{ring}", CX + 3.8, CY - C.RING_R[ring], 0, "F.SilkS", 1.5, 0.2)
    tri = [(CX - 1.2, CY - 19.6), (CX + 1.2, CY - 19.6), (CX, CY - 17.4)]
    o += K.gr_poly(uid, "tri", tri)
    o += K.gr_text(uid, "title", "CONTACT SIDE", CX, CY + 50.8, 0, "F.SilkS", 1.2, 0.2)
    o += K.gr_text(uid, "dir", "A-B-C " + ("CCW" if ccw else "CW") + " SEEN FROM THIS SIDE", CX, CY + 52.8, 0, "F.SilkS", 1.0, 0.15)
    for h, corner in C.CORNER_ORDER.items():
        n, u = CORNERS[corner]
        o += K.gr_text(uid, f"hb{h}", f"{h} = RING {h[1]}", CX + 36.5 * n[0] * 1.0, CY + 36.5 * n[1], 0, "B.SilkS", 1.2, 0.2, mirror=True)
    return o


def station_holes():
    p = C.POST
    return [("H1", CX - p, CY - p, 3.2), ("H2", CX + p, CY - p, 3.0), ("H3", CX - p, CY + p, 3.0), ("H4", CX + p, CY + p, 3.2)]


def build_station(nl: K.Netlist, ccw=True) -> str:
    uid = K.Ids(UID_NS)
    lib = K.FpLib({C.FP_LIB: HERE / "Christopher.pretty"})
    return K.build_pcb("gen_contact_pcb.py", "Gear bombe contact board (one drum station)", "A4",
                       ["Generated by gen_contact_pcb.py - placement only, routing by hand",
                        "Netlist from contact_board.kicad_sch; 4 layers; contacts front, ribbon headers back"],
                       nl, station_placements(ccw), lib, uid, holes=station_holes(), extra=station_extra(uid, ccw))


# ----------------------------------------------------------------------------- terminal and reflector card
TERM_W, TERM_H = 116.0, 62.0


def terminal_placements() -> dict:
    P = {}
    cx = TERM_W / 2
    for k, ref in enumerate(("J1", "J2")):
        P[ref] = dict(x=cx - 24.925, y=16.0 + 30.0 * k - 1.42, rot=0, hide=True)
    y1 = TERM_H / 2 - 15.24
    P["K1"] = dict(x=16.0, y=y1, rot=180, flip=True, hide=True)
    P["K2"] = dict(x=TERM_W - 12.0, y=y1, rot=180, flip=True, hide=True)
    for h, (x, y) in enumerate([(4.5, 4.5), (TERM_W - 4.5, 4.5), (4.5, TERM_H - 4.5), (TERM_W - 4.5, TERM_H - 4.5)], 1):
        P[f"H{h}"] = dict(x=x, y=y, rot=0, hide=True)
    return P


def build_terminal(nl: K.Netlist) -> str:
    uid = K.Ids("6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0e03")
    extra = K.edge_rect(uid, TERM_W, TERM_H)
    extra += K.gr_text(uid, "t1", "UNIT IN", TERM_W / 2 - 30.0, 16.0, 0, "F.SilkS", 2.0, 0.3)
    extra += K.gr_text(uid, "t2", "UNIT OUT", TERM_W / 2 - 30.0, 46.0, 0, "F.SilkS", 2.0, 0.3)
    extra += K.gr_text(uid, "t3", "K1 = IN RIBBON (LOWER STATION J4)   K2 = OUT RIBBON (J1)", TERM_W / 2, TERM_H - 3.0,
                       0, "B.SilkS", 1.0, 0.15, mirror=True)
    return K.build_pcb("gen_contact_pcb.py", "Gear bombe column terminal (unit IN / OUT)", "A4",
                       ["Generated by gen_contact_pcb.py - placement only, routing by hand",
                        "Netlist from column_terminal.kicad_sch; 4 layers; jacks front, ribbons back"],
                       nl, terminal_placements(), K.FpLib(), uid, extra=extra)


CARD_W, CARD_H = 56.0, 62.0


def card_placements() -> dict:
    y1 = CARD_H / 2 - 15.24
    P = {"K1": dict(x=18.0, y=y1, rot=180, flip=True, hide=True), "K2": dict(x=CARD_W - 12.0, y=y1, rot=180, flip=True, hide=True)}
    return P


def build_card(name: str, nl: K.Netlist) -> str:
    uid = K.Ids("6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0e04")
    R = C.reflector(name)
    extra = K.edge_rect(uid, CARD_W, CARD_H)
    extra += K.gr_text(uid, "t1", f"REFLECTOR {name}", CARD_W / 2, 6.0, 0, "F.SilkS", 2.0, 0.3)
    extra += K.gr_text(uid, "t2", "".join(C.L(R[j]) for j in range(C.N)), CARD_W / 2, 10.0, 0, "F.SilkS", 1.0, 0.15)
    extra += K.gr_text(uid, "t3", "K1 FROM RING 3   K2 TO RING 2", CARD_W / 2, CARD_H - 3.0, 0, "B.SilkS", 1.0, 0.15, mirror=True)
    return K.build_pcb("gen_contact_pcb.py", f"Gear bombe reflector card {name}", "A4",
                       ["Generated by gen_contact_pcb.py - placement only, routing by hand",
                        f"Netlist from reflector_{name}.kicad_sch; 4 layers"],
                       nl, card_placements(), K.FpLib(), uid, extra=extra,
                       holes=[(f"H{h}", x, y, 3.2) for h, (x, y) in enumerate(
                           [(4.5, 4.5), (CARD_W - 4.5, 4.5), (4.5, CARD_H - 4.5), (CARD_W - 4.5, CARD_H - 4.5)], 1)])


# ----------------------------------------------------------------------------- main
def main():
    ccw = "--contacts-cw" not in sys.argv
    jobs = [("contact_board", lambda nl: build_station(nl, ccw)), ("column_terminal", build_terminal),
            ("reflector_B", lambda nl: build_card("B", nl)), ("reflector_C", lambda nl: build_card("C", nl))]
    for proj, fn in jobs:
        with tempfile.TemporaryDirectory() as td:
            nl = K.Netlist.export(HERE / f"{proj}.kicad_sch", Path(td))
        (HERE / f"{proj}.kicad_pcb").write_text(fn(nl), encoding="utf8", newline="\n")
        K.merge_board_rules(HERE / f"{proj}.kicad_pro")
        print(f"wrote {proj}.kicad_pcb")


if __name__ == "__main__":
    main()
