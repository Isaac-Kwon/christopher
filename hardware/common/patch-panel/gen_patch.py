#!/usr/bin/env python3
"""Generate the KiCad 10 schematic of the menu patch panel board (the small board behind the operator panel).

Decision (README.md): the 52 letter jacks live on the five diagonal boards (hardware/common/diagonal-board); this board
carries everything else the design brief 4.3 puts on the panel:
  * commons: 4 groups x 4 male D-sub 37 jacks, the four jacks of a group in parallel (26 lines),
  * the test-register cable jack JR1 (front, operator side) with JR2 (rear, the register's J1 cable), in parallel,
  * the searching (test-voltage) set: jack JS1 whose 26 lines go to a 26-hole field TS1 (hole k = wire k); the
    test-voltage lead (register J5: TEST, 0 V) ends in the plug PL1 that is pushed into ONE hole,
  * 0 V reference: pins 27-29 of every jack tied to GND here (common side, decision 0003 5.2); J0V = the single
    connection to the 0 V of the power supply; shells and mounting holes = CHASSIS, CHASSIS - 0 V by 1 Mohm || 10 nF.

    python gen_patch.py            # writes patch_panel.kicad_pro/.kicad_sch
"""
from __future__ import annotations

import sys
from pathlib import Path

import ki_common as K

HERE = Path(__file__).resolve().parent
NS = "6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0f01"
PROJECT = "patch_panel"
N = 26

FP_DSUB = "Connector_Dsub:DSUB-37_Pins_Vertical_P2.77x2.84mm_MountingHoles"
FP_TS = "Connector_PinSocket_2.54mm:PinSocket_2x13_P2.54mm_Vertical"
FP_HOLE = "MountingHole:MountingHole_3.2mm_M3_Pad"
FP_R = "Resistor_SMD:R_0603_1608Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_TB2 = "TerminalBlock_Phoenix:TerminalBlock_Phoenix_MKDS-1,5-2-5.08_1x02_P5.08mm_Horizontal"

S_DSUB = K.Sym("Connector", "DC37_Pins_MountingHoles")
S_TS = K.Sym("Connector_Generic", "Conn_02x13_Odd_Even")
S_PL = K.Sym("Connector_Generic", "Conn_01x01")
S_HOLE = K.Sym("Mechanical", "MountingHole_Pad")
S_R = K.Sym("Device", "R_US")
S_C = K.Sym("Device", "C")
S_TB2 = K.Sym("Connector", "Screw_Terminal_01x02")

L = lambda i: chr(65 + i)
COMMONS = [(g, n) for g in range(1, 5) for n in range(1, 5)]       # CM<g><n>
SLOTS = [f"CM{g}{n}" for g, n in COMMONS] + ["JR1", "JR2", "JS1"]    # jack order on the board (row-major)
NET = {**{f"CM{g}{n}": f"C{g}" for g, n in COMMONS}, "JR1": "REG", "JR2": "REG", "JS1": "SEL"}
DESC = {"JR1": "Test register cable jack (front): plug the register cable end here, or a cable to the test letter's jack",
        "JR2": "Test register cable jack (rear): cable to the test register J1; parallel with JR1",
        "JS1": "Searching jack: a 26-line cable from the second jack of the test letter; line k -> hole k of TS1"}
N_HOLES = 6


def build() -> K.Sheet:
    ids = K.Ids(NS)
    sh = K.Sheet(ids, PROJECT, "A1", "Menu patch panel board: commons, register jack, searching set, 0 V reference",
                 ["Project Christopher - common part; generated by gen_patch.py (hardware/common/patch-panel/README.md)",
                  "Letter jacks are on the diagonal boards; this board: commons, register cable jack, test-voltage plug, 0 V ties",
                  "Jack pins 1-26 = wire A..Z, 27-29 = 0 V (tied here), shell = CHASSIS"],
                 inst_path=f"/{ids('sheetfile', PROJECT)}")
    for i, ref in enumerate(SLOTS):
        x = 50.0 + (i % 7) * 52.0
        y = 70.0 + (i // 7) * 135.0
        tag = NET[ref]
        nets = {str(k + 1): f"{tag}_{L(k)}" for k in range(N)}
        nets.update({"27": "GND", "28": "GND", "29": "GND", "SH": "CHASSIS"})
        if ref.startswith("CM"):
            d = f"Common {ref[2]} jack {ref[3]} (male D-sub 37): 26 lines in parallel with the other three jacks of the group"
            val = f"COMMON_{ref[2]}_{ref[3]}"
        else:
            d, val = DESC[ref], ref
        sh.part(S_DSUB, x, y, ref, val, FP_DSUB, nets, "", d, length=5.08)
    y0 = 460.0
    # 26-hole field: hole k = wire k
    sh.part(S_TS, 50.0, y0, "TS1", "SEARCH_HOLES", FP_TS, {str(k + 1): f"SEL_{L(k)}" for k in range(N)}, "",
            "Searching hole field: hole k (A..Z) = wire k of the searching jack JS1; the test plug PL1 goes into one hole", length=5.08)
    sh.part(S_TB2, 130.0, y0, "J_TEST", "TEST_LEAD", FP_TB2, {"1": "TEST", "2": "GND"}, "",
            "Test voltage lead from the test register J5: 1 = TEST (+24 V while STROBE), 2 = 0 V", length=5.08)
    sh.part(S_PL, 190.0, y0, "PL1", "TEST_PLUG", "", {"1": "TEST"}, "",
            "Test plug on the end of the TEST lead (flying lead, pushed into one hole of TS1); not on the board",
            in_bom=True, on_board=False)
    sh.part(S_TB2, 250.0, y0, "J0V", "REF_0V", FP_TB2, {"1": "GND", "2": "GND"}, "",
            "0 V reference: connect to the 0 V of the power supply at ONE point (and to J0V of diagonal board D1). 1 and 2 are one net.",
            length=5.08)
    sh.part(S_R, 310.0, y0, "R1", "1M", FP_R, {"1": "CHASSIS", "2": "GND"}, "", "CHASSIS - 0 V, 1 Mohm || 10 nF (decision 0003 7.1)")
    sh.part(S_C, 340.0, y0, "C1", "10n/100V", FP_C, {"1": "CHASSIS", "2": "GND"}, "", "CHASSIS - 0 V, 10 nF 100 V X7R")
    for h in range(N_HOLES):
        sh.part(S_HOLE, 380.0 + h * 20.0, y0, f"H{h + 1}", "M3_CHASSIS", FP_HOLE, {"1": "CHASSIS"}, "",
                "M3 mounting hole, plated, CHASSIS", in_bom=False)
    sh.text("Menu patch panel board (common part).  Commons: four groups of four jacks, 26 lines parallel within a group.\n"
            "Register: JR1 (front) / JR2 (rear) parallel.  Searching: JS1 line k -> TS1 hole k; plug PL1 (TEST) into hole k puts the\n"
            "test voltage on wire k of the cable on JS1 (the wire the menu uses as input wire).  Pins 27-29 of all jacks = GND (tied here).", 40, 20)
    return sh


def main(outdir: Path = HERE):
    sh = build()
    K.write_project_and_sheet(outdir, PROJECT, sh)
    print(f"wrote {PROJECT}.kicad_sch")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE)
