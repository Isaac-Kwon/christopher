#!/usr/bin/env python3
"""Generate the KiCad 10 PCB of the menu patch panel board: deterministic PLACEMENT only (no routing).

    python gen_patch_pcb.py        # exports the schematic netlist with kicad-cli, writes patch_panel.kicad_pcb

Scheme: 4 layers (routing of the 26-line commons).  Front (panel side): 19 male D-sub 37 jacks (vertical footprint, shells through the panel) on a
85 x 30 mm grid - rows 1-4 = commons 1-4 (4 jacks each), row 5 = JR1, JR2 (register cable), JS1 (searching) and,
in the fourth slot, the 26-hole field TS1 (A..Z), the test lead terminal J_TEST and the 0 V reference terminal J0V.
The flying test plug PL1 is not on the board.
"""
from __future__ import annotations

import sys
import tempfile
from pathlib import Path

import gen_patch as G
import ki_common as K

HERE = Path(__file__).resolve().parent
UID_NS = "6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0f02"

JACK_CX, JACK_CY = 24.925, 1.42
JACK_L, JACK_R = -10.32, 60.17
ROW0, ROW_PITCH, COL_PITCH = 18.0, 30.0, 85.0
X0 = 4.0 + 3.0 - JACK_L              # pin-1 x of slot 0
BOARD_H = 160.0
BOARD_W = round(X0 + 3 * COL_PITCH + JACK_R + 3.0 + 4.0, 2)


def jack_pin1(slot: int, row: int) -> tuple[float, float]:
    return X0 + COL_PITCH * slot, ROW0 + ROW_PITCH * row - JACK_CY


def placements() -> dict:
    P = {}
    for g in range(1, 5):
        for n in range(1, 5):
            x, y = jack_pin1(n - 1, g - 1)
            P[f"CM{g}{n}"] = dict(x=x, y=y, rot=0, hide=True)
    for slot, ref in enumerate(("JR1", "JR2", "JS1")):
        x, y = jack_pin1(slot, 4)
        P[ref] = dict(x=x, y=y, rot=0, hide=True)
    L3 = X0 + 3 * COL_PITCH + JACK_L
    yc = ROW0 + ROW_PITCH * 4
    ts_x, ts_y = L3 + 1.81 + 0.5, yc - 1.27
    P["TS1"] = dict(x=ts_x, y=ts_y, rot=90, hide=True)        # pin 1 left, pins increase to the right, odd pins on the top row
    P["J_TEST"] = dict(x=ts_x + 32.3 + 7.0, y=yc, rot=0)
    P["J0V"] = dict(x=ts_x + 32.3 + 7.0 + 13.5, y=yc, rot=0)
    P["R1"] = dict(x=40.0, y=BOARD_H - 8.0, rot=0)
    P["C1"] = dict(x=55.0, y=BOARD_H - 8.0, rot=0)
    pts = [(6.0, 6.0), (BOARD_W - 6.0, 6.0), (6.0, BOARD_H - 6.0), (BOARD_W - 6.0, BOARD_H - 6.0),
           (BOARD_W / 2, 6.0), (BOARD_W / 2, BOARD_H - 6.0)]
    for h, (x, y) in enumerate(pts, 1):
        P[f"H{h}"] = dict(x=x, y=y, rot=0, hide=True)
    return P


def build(nl: K.Netlist) -> str:
    uid = K.Ids(UID_NS)
    P = placements()
    extra = K.edge_rect(uid, BOARD_W, BOARD_H)
    extra += K.gr_text(uid, "title", "MENU PATCH PANEL", BOARD_W / 2 + 40.0, 3.4, 0, "F.SilkS", 2.0, 0.3)
    for g in range(1, 5):
        for n in range(1, 5):
            x, y = jack_pin1(n - 1, g - 1)
            extra += K.gr_text(uid, f"c{g}{n}", f"COMMON {g}", x + JACK_CX, y + JACK_CY + 10.5, 0, "F.SilkS", 1.6, 0.25)
    for slot, (ref, t) in enumerate((("JR1", "REGISTER (FRONT)"), ("JR2", "REGISTER (REAR)"), ("JS1", "SEARCH"))):
        x, y = jack_pin1(slot, 4)
        extra += K.gr_text(uid, f"t{ref}", t, x + JACK_CX, y + JACK_CY + 10.5, 0, "F.SilkS", 1.6, 0.25)
    ts = P["TS1"]
    for k in range(26):
        col, row = k // 2, k % 2
        extra += K.gr_text(uid, f"ts{k}", G.L(k), ts["x"] + col * 2.54, ts["y"] + (-3.6 if row == 0 else 2.54 + 3.6), 0, "F.SilkS", 1.5, 0.2)
    extra += K.gr_text(uid, "tl", "TEST PLUG HOLE", ts["x"] + 15.0, ts["y"] - 8.0, 0, "F.SilkS", 1.4, 0.2)
    extra += K.gr_text(uid, "tt", "TEST / 0V", P["J_TEST"]["x"] + 2.5, P["J_TEST"]["y"] - 8.0, 0, "F.SilkS", 1.2, 0.2)
    extra += K.gr_text(uid, "t0", "REF 0V", P["J0V"]["x"] + 2.5, P["J0V"]["y"] - 8.0, 0, "F.SilkS", 1.2, 0.2)
    lib = K.FpLib()
    return K.build_pcb("gen_patch_pcb.py", "Menu patch panel board", "A2",
                       ["Generated by gen_patch_pcb.py - placement only, routing by hand",
                        "Netlist from patch_panel.kicad_sch; 4 layers; test plug PL1 is a flying lead (not on the board)"],
                       nl, P, lib, uid, extra=extra, four_layers=True, skip_refs=("PL1",))


def main():
    with tempfile.TemporaryDirectory() as td:
        nl = K.Netlist.export(HERE / f"{G.PROJECT}.kicad_sch", Path(td))
    (HERE / f"{G.PROJECT}.kicad_pcb").write_text(build(nl), encoding="utf8", newline="\n")
    K.merge_board_rules(HERE / f"{G.PROJECT}.kicad_pro")
    print(f"wrote {G.PROJECT}.kicad_pcb ({len(placements())} parts, {BOARD_W} x {BOARD_H} mm)")


if __name__ == "__main__":
    main()
