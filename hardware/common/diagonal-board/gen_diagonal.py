#!/usr/bin/env python3
"""Generate the five KiCad 10 schematics of the diagonal board (Welchman's diagonal board, split in five).

Letters per board 6/6/6/4/4 (docs/decisions/0002-gear-detail-decisions.md section 9,
hardware/common/diagonal-board.md): D1 = A B C N O P, D2 = D E F Q R S, D3 = G H I T U V,
D4 = J K W X, D5 = L M Y Z.  Every letter has two 26-line jacks (male D-sub 37, pins 1-26 = wire A..Z,
27-29 = 0 V reference tied HERE on the common side, shell = CHASSIS), wired in parallel.
The diagonal link: wire w of letter c  <->  wire c of letter w (325 links, own wire c of letter c unlinked).

Between boards: 3 x 64-pin IDC headers per boundary (XRn on the right edge of board k, XLn in the gap between
jack columns 1 and 2 of board k+1: gen_diagonal_pcb.py), ribbon pin p <-> pin p of the same index n.  A link {X, Y} crossing a boundary takes
the next free junction pin in the sorted list of the crossing links; links passing over a board connect
its left and right header pins.  Junction connector 3 pins 61-64 carry the 0 V reference.

    python gen_diagonal.py            # writes d1..d5 .kicad_pro/.kicad_sch
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.dont_write_bytecode = True
import ki_common as K  # noqa: E402

HERE = Path(__file__).resolve().parent
N = 26
IDS_NS = "6f1c2b0e-52a1-4a43-9c1b-0b0b0b0b0d01"

# (board name, jack columns left to right: (upper letter, lower letter))
BOARDS = [
    ("d1", [("A", "N"), ("B", "O"), ("C", "P")]),
    ("d2", [("D", "Q"), ("E", "R"), ("F", "S")]),
    ("d3", [("G", "T"), ("H", "U"), ("I", "V")]),
    ("d4", [("J", "W"), ("K", "X")]),
    ("d5", [("L", "Y"), ("M", "Z")]),
]
NB = len(BOARDS)
CONN = 3                 # junction connectors per boundary
CONN_PINS = 64
GND_PINS = (61, 62, 63, 64)      # on junction connector 3
GND_CONN = CONN

FP_DSUB = "Connector_Dsub:DSUB-37_Pins_Vertical_P2.77x2.84mm_MountingHoles"
FP_IDC = "Connector_IDC:IDC-Header_2x32_P2.54mm_Vertical"
FP_HOLE = "MountingHole:MountingHole_3.2mm_M3_Pad"
FP_R = "Resistor_SMD:R_0603_1608Metric"
FP_C = "Capacitor_SMD:C_0805_2012Metric"
FP_TB2 = "TerminalBlock_Phoenix:TerminalBlock_Phoenix_MKDS-1,5-2-5.08_1x02_P5.08mm_Horizontal"


def board_letters(k: int) -> list[str]:
    return [c for col in BOARDS[k][1] for c in col]


def board_of(c: str) -> int:
    for k in range(NB):
        if c in board_letters(k):
            return k
    raise KeyError(c)


def links() -> list[tuple[str, str]]:
    """The 325 diagonal links as sorted letter pairs (x < y)."""
    L = [chr(65 + i) for i in range(N)]
    return [(L[i], L[j]) for i in range(N) for j in range(i + 1, N)]


def link_net(x: str, y: str) -> str:
    x, y = sorted((x, y))
    return f"L_{x}{y}"


def jack_net(c: str, w: str) -> str:
    """Net of wire w (letter) on a jack of letter c."""
    return f"S_{c}" if c == w else link_net(c, w)


def crossing(b: int) -> list[tuple[str, str]]:
    """Links that cross boundary b (between board b and b+1), sorted by (x, y)."""
    return [(x, y) for x, y in links() if min(board_of(x), board_of(y)) <= b < max(board_of(x), board_of(y))]


def junction_pin(b: int, x: str, y: str) -> tuple[int, int]:
    """(connector 1..3, pin 1..64) of link {x, y} at boundary b."""
    i = crossing(b).index((x, y))
    assert i < CONN * CONN_PINS - len(GND_PINS)
    return i // CONN_PINS + 1, i % CONN_PINS + 1


def jack_ref(c: str, n: int) -> str:
    return f"J{c}{n}"


S_DSUB = K.Sym("Connector", "DC37_Pins_MountingHoles")
S_IDC = K.Sym("Connector_Generic", "Conn_02x32_Odd_Even")
S_HOLE = K.Sym("Mechanical", "MountingHole_Pad")
S_R = K.Sym("Device", "R_US")
S_C = K.Sym("Device", "C")
S_TB2 = K.Sym("Connector", "Screw_Terminal_01x02")


def build_sheet(k: int) -> K.Sheet:
    name, cols = BOARDS[k]
    ids = K.Ids(IDS_NS)
    letters = board_letters(k)
    sh = K.Sheet(ids, name, "A1", f"Diagonal board D{k + 1}: letters {' '.join(letters)}",
                 [f"Part {k + 1} of 5 of Welchman's diagonal board (hardware/common/diagonal-board.md)",
                  "Generated by gen_diagonal.py - do not edit by hand",
                  "Jack pin w = wire w of the letter's cable; link wire w of c <-> wire c of w. Pins 27-29 = 0 V, shell = CHASSIS"],
                 inst_path=f"/{ids('sheetfile', name)}")
    # letter jacks, two per letter, in the panel order: A-M group upper, N-Z group lower
    jx0, jy = 60.0, 70.0
    for ci, (up, lo) in enumerate(cols):
        for r, c in enumerate((up, lo)):
            for n in (1, 2):
                idx = ord(c) - 65
                nets = {str(w + 1): jack_net(c, chr(65 + w)) for w in range(N)}
                nets.update({"27": "GND", "28": "GND", "29": "GND", "SH": "CHASSIS"})
                x = jx0 + ci * 90.0 + (n - 1) * 45.0
                y = jy + r * 140.0
                sh.part(S_DSUB, x, y, jack_ref(c, n), f"LETTER_{c}_{n}", FP_DSUB, nets, "",
                        f"Letter {c} jack {n} (male D-sub 37): pins 1-26 = wire A..Z of cable {c}, 27-29 = 0 V, parallel with jack {3 - n}",
                        length=5.08)
    # junction headers (3 left if k > 0, 3 right if k < NB-1)
    hx0, hy = 40.0, 400.0
    sides = []
    if k > 0:
        sides += [("XL", k - 1, False)]
    if k < NB - 1:
        sides += [("XR", k, True)]
    pos = 0
    for tag, b, is_right in sides:
        cross = crossing(b)
        for conn in range(1, CONN + 1):
            nets = {}
            for i, (x_, y_) in enumerate(cross):
                if i // CONN_PINS + 1 == conn:
                    nets[str(i % CONN_PINS + 1)] = link_net(x_, y_)
            if conn == GND_CONN:
                for p in GND_PINS:
                    nets[str(p)] = "GND"
            x = hx0 + pos * 62.0
            other = f"D{b + 2}" if is_right else f"D{b + 1}"
            where = "right edge" if is_right else "gap between jack columns 1 and 2"
            sh.part(S_IDC, x, hy, f"{tag}{conn}", f"{tag}{conn}_{other}", FP_IDC, nets, "",
                    f"Junction ribbon {conn} of 3 to board {other} ({where}): 64-way flat cable 1:1",
                    length=5.08)
            pos += 1
    # 0 V terminal on D1, chassis RC, mounting holes
    ox = 40.0 + pos * 62.0 + 20.0
    sh.part(S_R, ox, hy, "R1", "1M", FP_R, {"1": "CHASSIS", "2": "GND"}, "", "CHASSIS - 0 V, 1 Mohm in parallel with C1 (decision 0003 7.1)")
    sh.part(S_C, ox + 30, hy, "C1", "10n/100V", FP_C, {"1": "CHASSIS", "2": "GND"}, "", "CHASSIS - 0 V, 10 nF 100 V X7R")
    nh = 6 if len(letters) == 6 else 4
    for h in range(nh):
        sh.part(S_HOLE, ox + 60 + h * 20.0, hy, f"H{h + 1}", "M3_CHASSIS", FP_HOLE, {"1": "CHASSIS"}, "",
                "M3 mounting hole, plated, CHASSIS", in_bom=False)
    if k == 0:
        sh.part(S_TB2, ox, hy + 40, "J0V", "REF_0V", FP_TB2, {"1": "GND", "2": "GND"}, "",
                "0 V reference of the letter jacks (pins 27-29): connect to the 0 V of the common part at ONE point (patch panel J0V). 1 and 2 are the same net (loop-through).",
                length=5.08)
    sh.text(f"Diagonal board D{k + 1} of 5 - letters {' '.join(letters)} ({len(letters)} letters, {2 * len(letters)} jacks).\n"
            "Link net L_XY joins wire Y of letter X and wire X of letter Y on all four jacks of the two letters; S_X = own wire of letter X.\n"
            "Junction headers: 3 per boundary, ribbon pin n <-> pin n; links sorted by (X,Y) take connector (i // 64 + 1), pin i % 64 + 1.\n"
            "Connector 3 pins 61-64 = 0 V reference (GND), tied to every jack pins 27-29 and to the single power-0V terminal J0V (D1).\n"
            "Shells and mounting holes = CHASSIS; CHASSIS - 0 V by 1 Mohm || 10 nF (R1, C1).", 40, 30)
    return sh


def main(outdir: Path = HERE):
    for k in range(NB):
        sh = build_sheet(k)
        K.write_project_and_sheet(outdir, BOARDS[k][0], sh)
        print(f"wrote {BOARDS[k][0]}.kicad_sch: {len(board_letters(k))} letters, {sum(1 for i in sh.items if i.startswith(chr(9) + '(symbol'))} symbols")
    cr = [len(crossing(b)) for b in range(NB - 1)]
    print("links:", len(links()), "crossing per boundary:", cr)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else HERE)
