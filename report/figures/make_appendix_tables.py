"""Generate the data tables of appendices B (wiring) and C (verification vectors).

    python report/figures/make_appendix_tables.py

Reads the single sources of truth — data/wirings/enigma.txt, data/vectors/historical.json and
data/vectors/rtl/* — and writes report/figures/generated/{wirings,vectors}.tex, so no table is
copied by hand. The wiring table is re-checked (permutation; reflector = fixed-point-free involution).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "report" / "figures" / "generated"
A = ord("A")


def tex(s: str) -> str:
    return s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("&", "\\&").replace("%", "\\%").replace("#", "\\#")


def brk(s: str) -> str:
    """Monospace name that may break after - and _ (long file names in narrow table columns)."""
    return "\\texttt{" + tex(s).replace("-", "-\\allowbreak{}").replace("\\_", "\\_\\allowbreak{}") + "}"


def spaced(s: str, group: int = 26) -> str:
    return "\\,".join(s[i:i + group] for i in range(0, len(s), group))


def groups(s: str, n: int = 5) -> str:
    return " ".join(s[i:i + n] for i in range(0, len(s), n))


# ---------------------------------------------------------------------------------------------
# Appendix B — wiring
# ---------------------------------------------------------------------------------------------
def wirings() -> str:
    rows = []
    for raw in (ROOT / "data" / "wirings" / "enigma.txt").read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line:
            kind, name, wiring, turnover = line.split()
            rows.append((kind, name.upper(), wiring.upper(), turnover))
    for kind, name, w, _ in rows:
        assert sorted(w) == [chr(A + i) for i in range(26)], f"{name}: not a permutation"
        if kind == "reflector":
            for i, c in enumerate(w):
                j = ord(c) - A
                assert j != i and ord(w[j]) - A == i, f"{name}: not a fixed-point-free involution"

    def inverse(w: str) -> str:
        inv = [""] * 26
        for i, c in enumerate(w):
            inv[ord(c) - A] = chr(A + i)
        return "".join(inv)

    out = [
        "% GENERATED by report/figures/make_appendix_tables.py from data/wirings/enigma.txt — do not edit.",
        "\\begin{table}[ht]\\centering\\footnotesize",
        "\\caption{로터와 그리스 로터의 배선(코어 오프셋 0). 입력 글자 A--Z 아래에 출력 글자를 적었다. 역배선은 "
        "반사판 쪽에서 들어오는 오는 길이다. 넘김 글자는 그 글자가 창에 보일 때 다음 키에서 왼쪽 로터를 함께 돌린다.}",
        "\\label{tab:app-rotors}",
        "\\begin{tabular}{@{}l l l c@{}}\\toprule",
        "로터 & 배선 (입력 A--Z) & 역배선 & 넘김\\\\\\midrule",
        "입력 & \\texttt{ABCDEFGHIJKLMNOPQRSTUVWXYZ} & \\texttt{ABCDEFGHIJKLMNOPQRSTUVWXYZ} & \\\\\\midrule",
    ]
    for kind, name, w, t in rows:
        if kind in ("rotor", "greek"):
            label = name if kind == "rotor" else name.capitalize()
            turn = "---" if t == "-" else t
            out.append(f"{label} & \\texttt{{{w}}} & \\texttt{{{inverse(w)}}} & {turn}\\\\")
    out += ["\\bottomrule\\end{tabular}", "\\end{table}", ""]

    out += [
        "\\begin{table}[ht]\\centering\\footnotesize",
        "\\caption{반사판의 배선. 반사판은 글자를 둘씩 맞바꾸는 대합(involution)이고 고정점이 없다. 그래서 "
        "에니그마는 어떤 글자도 자기 자신으로 암호화하지 않는다(크립 정렬의 근거, \\ref{sec:crib}절). "
        "얇은 반사판(B-THIN, C-THIN)은 M4에서 그리스 로터와 함께 쓴다.}",
        "\\label{tab:app-reflectors}",
        "\\begin{tabular}{@{}l l l@{}}\\toprule",
        "반사판 & 배선 (입력 A--Z) & 맞바뀌는 쌍\\\\\\midrule",
    ]
    for kind, name, w, _ in rows:
        if kind == "reflector":
            pairs = sorted({"".join(sorted((chr(A + i), c))) for i, c in enumerate(w)})
            out.append(f"{name} & \\texttt{{{w}}} & \\texttt{{\\footnotesize {' '.join(pairs)}}}\\\\")
    out += ["\\bottomrule\\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------
# Appendix C — verification vectors
# ---------------------------------------------------------------------------------------------
def vectors() -> str:
    hist = json.loads((ROOT / "data" / "vectors" / "historical.json").read_text(encoding="utf-8"))
    out = [
        "% GENERATED by report/figures/make_appendix_tables.py from data/vectors — do not edit.",
        "\\begin{table}[ht]\\centering\\footnotesize",
        "\\caption{실제 전문 벡터(\\code{data/vectors/historical.json}). 링과 시작 위치는 왼쪽부터(M4는 그리스 로터가 맨 "
        "앞). 확인 열은 저장소의 시험(\\code{crates/christopher-core/tests/historical.rs})이 무엇을 대조하는지다.}",
        "\\label{tab:app-historical}",
        "\\begin{tabular}{@{}p{3.4cm} l p{2.2cm} l r p{3.4cm}@{}}\\toprule",
        "벡터 & 기종 & 로터 순서 & 링 / 시작 & 길이 & 확인\\\\\\midrule",
    ]
    for v in hist:
        order = f"{v['reflector']} " + (f"{v['greek'].capitalize()} " if v.get("greek") else "") + "-".join(v["rotors"])
        check = ("공개 평문과 전체 일치" if v["plaintext"] else "공개 평문 없음; 해독문이 독일어 통계로 암호문보다 뚜렷이 높음")
        out.append(f"{brk(v['id'])} & {tex(v['machine'])} & {tex(order)} & \\texttt{{{v['rings']}}} / "
                   f"\\texttt{{{v['start']}}} & {len(v['ciphertext'])} & {check}\\\\")
    out += ["\\bottomrule\\end{tabular}", "\\end{table}", ""]
    for v in hist:
        out += [
            f"\\paragraph{{\\code{{{tex(v['id'])}}}.}} 플러그보드 \\texttt{{{v['plugboard']}}}. 출처: \\url{{{v['source'].split()[0].rstrip(';,')}}}.",
            "\\begin{quote}\\footnotesize\\ttfamily",
            "암호문(앞 50자): " + groups(v["ciphertext"][:50]) + "\\\\",
        ]
        if v["plaintext"]:
            out.append("평문(앞 50자): " + groups(v["plaintext"][:50]))
        out += ["\\end{quote}", ""]

    rtl = ROOT / "data" / "vectors" / "rtl"
    out += [
        "\\begin{table}[ht]\\centering\\footnotesize",
        "\\caption{회로 검증 벡터(\\code{data/vectors/rtl/}). 위: \\code{bombe\\_core} 한 위치씩의 벡터(676선 고정점 전체 "
        "\\code{live}와 정지 여부). 아래: \\code{bombe\\_sweep}·FPGA 엔진이 순서까지 맞춰야 하는 전체 구동의 정지 목록. "
        "모두 Rust 코어(\\code{Bombe.trace}, \\code{Bombe.run})가 낸 값이다.}",
        "\\label{tab:app-rtl}",
        "\\begin{tabular}{@{}p{4.6cm} l r r r p{2.4cm}@{}}\\toprule",
        "파일 & 로터 순서 & 연결 & 벡터 & 정지 & 조건\\\\\\midrule",
    ]
    for f in sorted(rtl.glob("*.jsonl")):
        lines = [json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()]
        first = lines[0]
        cond = []
        if first.get("diagonal") is False:
            cond.append("대각선 보드 없음")
        if first.get("turnover_at") is not None:
            cond.append(f"넘김 가설 {first['turnover_at']}")
        out.append(f"{brk(f.name)} & {tex(first['wheel_order'])} & {len(first['edges'])} & {len(lines)} & "
                   f"{sum(1 for x in lines if x['stop'])} & {', '.join(cond) or '---'}\\\\")
    out.append("\\midrule")
    out.append("파일 & 로터 순서 & 연결 & 위치 & 정지 & 조건\\\\\\midrule")
    for f in sorted(rtl.glob("sweep_*.json")):
        d = json.loads(f.read_text(encoding="utf-8"))
        cond = []
        if d.get("diagonal") is False:
            cond.append("대각선 보드 없음")
        if d.get("turnover_at") is not None:
            cond.append(f"넘김 가설 {d['turnover_at']}")
        out.append(f"{brk(f.name)} & {tex(d['wheel_order'])} & {len(d['edges'])} & {d['positions_tested']:,} & "
                   f"{len(d['stops']):,} & {', '.join(cond) or '---'}\\\\")
    out += ["\\bottomrule\\end{tabular}", "\\end{table}", ""]
    return "\n".join(out)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, body in (("wirings.tex", wirings()), ("vectors.tex", vectors())):
        (OUT / name).write_text(body, encoding="utf-8", newline="\n")
        print(f"report/figures/generated/{name}")


if __name__ == "__main__":
    main()
