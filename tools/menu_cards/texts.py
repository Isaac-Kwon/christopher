def message_by_id(msg_id: str) -> tuple[str, str, list[str]]:
    for m in MESSAGES:
        if m[0] == msg_id:
            return m
    raise KeyError(msg_id)


def clean(text: str) -> str:
    return "".join(c for c in text.upper() if "A" <= c <= "Z")
